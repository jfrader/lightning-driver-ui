// Generates TypeScript types and standalone response/request validators from the frozen
// backend-owned contract snapshot. `--check` fails when the snapshot hash or generated
// files drift. Never edit contract/openapi.v1.json or src/api/generated/* by hand.
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import { _ } from 'ajv';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import addFormats from 'ajv-formats';
import { build } from 'esbuild';

// Frozen backend-owned API v1 (GURI-2908). The snapshot is a consumer copy; change it only by
// copying a newly frozen revision and updating these hashes.
const FROZEN_SHA256 = 'a7bd38f4dbf398f47617b1aa08fb216bbae12b357619ab4215548577a750cad5';
const FROZEN_EXAMPLES_SHA256 = '889dce55d785b4ee02cc26ad2b36ffe988dcc41dfbac36c9052ec2be96b58d35';
const CONTRACT_URL = new URL('../contract/openapi.v1.json', import.meta.url);
const EXAMPLES_URL = new URL('../contract/examples.v1.json', import.meta.url);
const ROOT = fileURLToPath(new URL('..', import.meta.url));
const CONTRACT_ID ='https://contract.lightning-driver.invalid/openapi.v1.json';
const SCHEMA_OUT = new URL('../src/api/generated/schema.ts', import.meta.url);
const VALIDATORS_OUT = new URL('../src/api/generated/validators.js', import.meta.url);
const VALIDATORS_TYPES_OUT = new URL('../src/api/generated/validators.d.ts', import.meta.url);
const HEADER = '// Generated by scripts/api-contract.mjs from contract/openapi.v1.json. Do not edit.\n';

const VALIDATED_SCHEMAS = [
  'AuthBootstrap',
  'AuthenticationChallenge',
  'RegistrationChallenge',
  'Session',
  'PublicPolicy',
  'NodesPage',
  'NodeSummary',
  'NodeInfo',
  'NodePolicy',
  'FeeEstimates',
  'Balances',
  'InvoicesPage',
  'PaymentsPage',
  'PeersPage',
  'ChannelsPage',
  'TransactionsPage',
  'DecodedInvoice',
  'CreateOperationRequest',
  'ConfirmOperationRequest',
  'AuthorizationStart',
  'OperationAuthorization',
  'Operation',
  'OperationsPage',
  'ErrorResponse',
  'NostrChallenge',
  'NostrEvent',
  'NostrIdentityResponse',
  'NostrRemoved',
  'NostrAuthorizationStart',
];

// Success bodies the contract declares inline rather than as a named schema: validator name to
// the operationId whose 200 JSON response it checks.
const VALIDATED_RESPONSES = {
  NostrIdentities: 'listNostrIdentities',
};

function operationResponseSchema(document, operationId) {
  for (const item of Object.values(document.paths)) {
    for (const operation of Object.values(item)) {
      if (operation?.operationId === operationId) return operation.responses['200'].content['application/json'].schema;
    }
  }
  throw new Error(`No operation ${operationId} in the contract`);
}

// A response schema compiled on its own resolves the contract's local refs against the contract.
function withContractRefs(schema) {
  if (Array.isArray(schema)) return schema.map(withContractRefs);
  if (typeof schema !== 'object' || schema === null) return schema;
  return Object.fromEntries(
    Object.entries(schema).map(([key, value]) => [
      key,
      key === '$ref' && typeof value === 'string' && value.startsWith('#/') ? `${CONTRACT_ID}${value}` : withContractRefs(value),
    ]),
  );
}

async function readFrozen(url, expectedSha) {
  const bytes = await readFile(url);
  const sha = createHash('sha256').update(bytes).digest('hex');
  if (sha !== expectedSha) throw new Error(`${url.pathname} is ${sha}, expected frozen ${expectedSha}`);
  return bytes;
}

async function bundleForBrowser(moduleCode) {
  const result = await build({
    stdin: { contents: moduleCode, resolveDir: ROOT, sourcefile: 'validators.js', loader: 'js' },
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    legalComments: 'none',
    write: false,
    metafile: true,
    logLevel: 'error',
  });
  const [output] = result.outputFiles;
  // esbuild keeps output imports, or a `typeof require` shim with `__require("…")` calls, only
  // for modules it could not bundle; a browser cannot load either.
  const imports = Object.values(result.metafile.outputs).flatMap((file) => file.imports);
  if (imports.length > 0 || /typeof require\b|\b__require\("/.test(output.text)) {
    throw new Error(`Validators are not self-contained: ${JSON.stringify(imports)}`);
  }
  return output.text;
}

async function generate() {
  const bytes = await readFrozen(CONTRACT_URL, FROZEN_SHA256);
  await readFrozen(EXAMPLES_URL, FROZEN_EXAMPLES_SHA256);
  const document = JSON.parse(bytes.toString('utf8'));

  const schemaTs = HEADER + astToString(await openapiTS(document));

  // Full JSON Schema semantics: string formats via ajv-formats and code-point string lengths.
  // Ajv's standalone output refers to its runtime helpers with require(); esbuild bundles those
  // helpers into one self-contained browser ES module, as the Ajv standalone docs recommend.
  const ajv = new Ajv2020({
    code: { source: true, esm: true, lines: false, formats: _`require("ajv-formats/dist/formats").fullFormats` },
    allErrors: false,
    inlineRefs: false,
    strictSchema: true,
    strictTypes: false,
    strictRequired: false,
  });
  addFormats(ajv);
  ajv.addKeyword('example');
  ajv.addKeyword('discriminator');
  ajv.addKeyword('components');
  ajv.addSchema({ $id: CONTRACT_ID, components: { schemas: document.components.schemas } });
  const responseRefs = Object.entries(VALIDATED_RESPONSES).map(([name, operationId]) => {
    const id = `${CONTRACT_ID}/responses/${operationId}`;
    ajv.addSchema({ $id: id, ...withContractRefs(operationResponseSchema(document, operationId)) });
    return [name, id];
  });
  const refs = Object.fromEntries([
    ...VALIDATED_SCHEMAS.map((name) => [name, `${CONTRACT_ID}#/components/schemas/${name}`]),
    ...responseRefs,
  ]);
  const validatorsJs = HEADER + (await bundleForBrowser(standaloneCode(ajv, refs)));

  const validatorsDts = [
    HEADER,
    "import type { components, operations } from './schema';",
    '',
    'export interface ContractValidator<T> {',
    '  (data: unknown): data is T;',
    '  errors?: readonly { instancePath: string; message?: string }[] | null;',
    '}',
    '',
    ...VALIDATED_SCHEMAS.map(
      (name) => `export declare const ${name}: ContractValidator<components['schemas']['${name}']>;`,
    ),
    ...Object.entries(VALIDATED_RESPONSES).map(
      ([name, operationId]) =>
        `export declare const ${name}: ContractValidator<operations['${operationId}']['responses'][200]['content']['application/json']>;`,
    ),
    '',
  ].join('\n');

  return [
    [SCHEMA_OUT, schemaTs],
    [VALIDATORS_OUT, validatorsJs],
    [VALIDATORS_TYPES_OUT, validatorsDts],
  ];
}

const check = process.argv.includes('--check');
const outputs = await generate();
const stale = [];
for (const [url, content] of outputs) {
  if (check) {
    const current = await readFile(url, 'utf8').catch(() => null);
    if (current !== content) stale.push(url.pathname);
  } else {
    await writeFile(url, content);
  }
}
if (stale.length > 0) {
  console.error(`Generated API files are stale:\n${stale.join('\n')}\nRun npm run api:generate.`);
  process.exit(1);
}
console.log(check ? 'API contract snapshot and generated files are current.' : 'Generated API files.');
